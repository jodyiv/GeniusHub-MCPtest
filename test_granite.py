import time
import sys
from openai import OpenAI

# 1. Initialize the client targeting your Proxmox LXC container
# The API key 'ollama' is a dummy value required by the SDK but ignored by the local engine.
client = OpenAI(
    base_url="http://192.168.52.195:11434/v1",
    api_key="ollama"
)

def query_granite(prompt_text):
    print(f"Connecting to Granite-Optimized API... sending prompt.\n")
    start_time = time.time()
    
    try:
        # 2. Trigger a streaming completion request to monitor real-time token delivery
        stream = client.chat.completions.create(
            model="granite-optimized",
            messages=[
                {
                    "role": "system", 
                    "content": "You are a concise, helpful IT assistant. Answer directly and cleanly."
                },
                {
                    "role": "user", 
                    "content": prompt_text
                }
            ],
            stream=True,
        )
        
        print("--- Granite Response ---")
        token_count = 0
        for chunk in stream:
            if chunk.choices[0].delta.content is not None:
                # Print tokens as they are generated by your Xeon CPUs
                sys.stdout.write(chunk.choices[0].delta.content)
                sys.stdout.flush()
                token_count += 1
                
        end_time = time.time()
        elapsed = end_time - start_time
        
        print("\n------------------------")
        print(f"Performance Metrics:")
        print(f"  - Total Inference Time: {elapsed:.2f} seconds")
        print(f"  - Estimated Speed: {token_count / elapsed:.2f} tokens/second")
        
    except Exception as e:
        print(f"\nAn error occurred connecting to the API: {e}")
        print("Please double check that your LXC firewall is open on port 11434.")

if __name__ == "__main__":
    # Test prompt to evaluate model performance and logic mapping
    test_prompt = "Explain why it is optimal to restrict CPU execution threads to a single physical NUMA socket when running an LLM."
    query_granite(test_prompt)